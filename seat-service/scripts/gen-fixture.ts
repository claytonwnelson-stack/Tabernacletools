// Emits a C++ test fixture: tokens signed by THIS service code with a fixed test key, verified by the app's SeatClient (TweetNaCl).
import { writeFileSync } from "node:fs";
import { signEntitlement } from "../src/tokens.ts";
const seed = Buffer.alloc(32, 7); // test-only key
const pk8 = Buffer.concat([Buffer.from("302e020100300506032b657004220420", "hex"), seed]);
const priv = await crypto.subtle.importKey("pkcs8", pk8, { name: "Ed25519" }, true, ["sign"]);
const jwk = await crypto.subtle.exportKey("jwk", priv) as JsonWebKey;
const pubHex = Buffer.from(jwk.x!, "base64url").toString("hex");
const iat = 1_800_000_000;
const good = await signEntitlement(priv, { v: 1, aud: "com.tabernacletools", team: "t_fixture", mem: "u_fixture", role: "member", exp: iat + 20 * 86400, iat, off: iat + 30 * 86400 });
const leader = await signEntitlement(priv, { v: 1, aud: "com.tabernacletools", team: "t_fixture", mem: "u_lead", role: "leader", exp: iat + 45 * 86400, iat, off: iat + 30 * 86400 });
const out = `// GENERATED by seat-service/scripts/gen-fixture.ts - do not edit. Test-only key (seed 0x07 x32).
#pragma once
namespace seat_fixture {
static const char* kPublicKeyHex = "${pubHex}";
static const char* kMemberToken = "${good}";
static const char* kLeaderToken = "${leader}";
static const long long kIat = ${iat};
}
`;
writeFileSync(process.argv[2] ?? "seat_fixture.h", out); console.log("wrote", process.argv[2] ?? "seat_fixture.h", pubHex);
