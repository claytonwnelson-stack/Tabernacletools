#!/usr/bin/env python3
"""Builds resources/hymns/*.cho and core/model/HymnData.cpp from resources/hymns/_hymns*.txt.
Each hymn: '@@ id | title | text author | text year | TUNE | tune composer/source | tune year | key | bpm | time' then ChordPro body.
Only hymns whose text AND tune (and any translation) were published before 1931 and whose authors died > 70 years ago."""
import glob, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
hy = []
for f in sorted(glob.glob(os.path.join(root, 'resources/hymns/_hymns*.txt'))):
    for chunk in open(f, encoding='utf-8').read().split('@@ ')[1:]:
        head, body = chunk.split('\n', 1)
        p = [x.strip() for x in head.split('|')]
        assert len(p) == 10, head
        hy.append(dict(id=p[0], title=p[1], author=p[2], tyear=int(p[3]), tune=p[4], composer=p[5], uyear=int(p[6]), key=p[7], bpm=int(p[8]), time=p[9], body=body.strip() + '\n'))
for h in hy:
    assert h['tyear'] < 1931 and h['uyear'] < 1931, h['id']
    h['basis'] = f"Text {h['tyear']}, tune {h['uyear']}: both published before 1931 (US public domain); all authors, translators and composers died over 70 years ago. Chords and section layout: original simple arrangement by Tabernacle Tools. Original verses only, no modern additions."
    h['cho'] = (f"{{title: {h['title']}}}\n{{artist: {h['author']}}}\n{{key: {h['key']}}}\n{{tempo: {h['bpm']}}}\n{{time: {h['time']}}}\n"
                f"{{meta: tune {h['tune']} - {h['composer']} ({h['uyear']})}}\n{{meta: public_domain {h['basis']}}}\n\n" + h['body'])
    open(os.path.join(root, 'resources/hymns', h['id'] + '.cho'), 'w', encoding='utf-8').write(h['cho'])
def q(s): return 'u8"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['// GENERATED by tools/gen_hymns.py from resources/hymns/_hymns*.txt - edit those, then re-run the script.', '#include "model/Hymns.h"', 'namespace wr {', 'const std::vector<Hymn>& hymnLibrary() {', '    static const std::vector<Hymn> v = {']
for h in hy:
    out.append(f"        {{ {q(h['id'])}, {q(h['title'])}, {q(h['author'])}, {h['tyear']}, {q(h['tune'])}, {q(h['composer'])}, {h['uyear']}, {q(h['basis'])},\n          R\"WRHYMN({h['cho']})WRHYMN\" }},")
out += ['    };', '    return v;', '}', '} // namespace wr', '']
open(os.path.join(root, 'core/model/HymnData.cpp'), 'w', encoding='utf-8').write('\n'.join(out))
print(len(hy), 'hymns')
